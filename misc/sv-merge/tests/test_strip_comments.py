import contextlib
import io
import tempfile
import unittest
from pathlib import Path

from sv_merge.cli import main
from sv_merge.merger import Merger
from sv_merge.source import mask_comments, strip_comments


class LexicalStripTests(unittest.TestCase):
    """Comment removal must keep line numbers and quoted strings intact."""

    def test_line_comment_removed_but_lines_kept(self):
        self.assertEqual(strip_comments('a // tail\nb\n'), 'a \nb\n')

    def test_block_comment_removed_but_lines_kept(self):
        # 5 lines in, 5 lines out: only the comment text vanishes.
        self.assertEqual(strip_comments('a\n/* x\ny\nz */\nb\n'), 'a\n\n\n\nb\n')

    def test_comment_only_line_becomes_empty_line(self):
        self.assertEqual(strip_comments('// only\n'), '\n')
        self.assertEqual(strip_comments('/* only */\n'), '\n')

    def test_strings_win_over_comment_markers(self):
        text = 'x = "http://a.b"; /* kill "quoted" */ y = "/*v*/";\n'
        self.assertEqual(strip_comments(text), 'x = "http://a.b";  y = "/*v*/";\n')

    def test_escaped_quote_inside_string_is_not_a_comment_start(self):
        self.assertEqual(strip_comments('s = "a\\" // b"; // gone\n'), 's = "a\\" // b"; \n')

    def test_continued_line_comment_is_fully_removed(self):
        # IEEE 1800-2017 22.5.1: // comment ends at newline unless continued.
        self.assertEqual(strip_comments('a // c1 \\\nc2\nb\n'), 'a \n\nb\n')

    def test_block_comment_does_not_nest(self):
        self.assertEqual(strip_comments('a /* p /* q */ b\nc\n'), 'a  b\nc\n')

    def test_unterminated_block_comment_is_an_error(self):
        with self.assertRaises(ValueError):
            strip_comments('a\nb /* open\nc\n')
        with self.assertRaises(ValueError):
            mask_comments('a\nb /* open\nc\n')

    def test_mask_hides_continued_comment_too(self):
        masked = mask_comments('a // c1 \\\nc2\nb\n')
        self.assertNotIn('c1', masked)
        self.assertNotIn('c2', masked)
        self.assertIn('b', masked)
        self.assertEqual(masked.count('\n'), 3)

    def test_mask_and_strip_keep_the_same_line_count(self):
        text = '// h\n`define A 1 /* v */ \\\n  + 2 // t\nstring "/*x*/ //y"\n/*\n*\n*/\nend\n'
        self.assertEqual(mask_comments(text).count('\n'), strip_comments(text).count('\n'))


class MergeStripTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.output = self.root / 'out.sv'

    def write(self, name, text):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        return str(path)

    def merge(self, paths, **kwargs):
        Merger(paths, str(self.output), verbose=False, **kwargs).run()
        return self.output.read_text()

    def cli(self, *args):
        with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
            return main(list(args))

    def test_output_contains_no_comment_markers(self):
        src = self.write('top.sv', '// header\nmodule m; /* body\nspanning */ wire w; // tail\nendmodule\n')
        result = self.merge([src], strip_comments=True)
        self.assertNotIn('//', result)
        self.assertNotIn('/*', result)
        self.assertNotIn('*/', result)
        self.assertIn('module m;', result)
        self.assertIn('wire w;', result)

    def test_line_numbers_are_preserved(self):
        src_text = '// a\nmodule m; /* b\nc */ wire w; // d\nendmodule\n'
        src = self.write('top.sv', src_text)
        stripped = self.merge([src], strip_comments=True)
        # One separator line is added per source file; the rest keeps line positions.
        self.assertEqual(stripped.count('\n'), src_text.count('\n') + 1)
        self.assertEqual(stripped.splitlines()[-1], 'endmodule')

    def test_default_output_keeps_comments_without_generated_banner(self):
        src = self.write('top.sv', '// keep me\nmodule m; endmodule\n')
        result = self.merge([src])
        self.assertNotIn('Generated by sv-merge', result)
        self.assertIn('FILE:', result)
        self.assertIn('// keep me', result)

    def test_tool_banners_are_suppressed_when_stripping(self):
        src = self.write('top.sv', 'module m; endmodule\n')
        other = self.write('pkg.sv', 'package p; endpackage\n')
        result = self.merge([src, other], strip_comments=True)
        self.assertNotIn('Generated by sv-merge', result)
        self.assertNotIn('FILE:', result)

    def test_defines_and_macros_are_preserved_verbatim(self):
        src = self.write('top.sv', '`define W 8 // width\n`define N /* inline */ 4\nmodule m; endmodule\n')
        result = self.merge([src], strip_comments=True)
        self.assertIn('`define W 8', result)
        self.assertIn('`define N', result)
        self.assertIn(' 4', result)

    def test_string_literals_survive_the_strip(self):
        src = self.write('top.sv', 'module m;\ninitial $display("http://a.b /* not a comment */");\nendmodule\n')
        result = self.merge([src], strip_comments=True)
        self.assertIn('"http://a.b /* not a comment */"', result)

    def test_included_headers_are_stripped_too(self):
        src = self.write('top.sv', '`include "defs.svh"\n')
        self.write('defs.svh', '// comment in header\n`define BODY 1 /* tail */\n')
        result = self.merge([src], strip_comments=True)
        self.assertNotIn('comment in header', result)
        self.assertIn('`define BODY 1', result)

    def test_stripped_include_with_trailing_comment_still_expands(self):
        src = self.write('top.sv', '`include "defs.svh" // why not\n')
        self.write('defs.svh', 'BODY\n')
        result = self.merge([src], strip_comments=True)
        self.assertIn('BODY', result)
        self.assertNotIn('why not', result)

    def test_guard_skips_are_reported_to_log_not_output(self):
        a = self.write('top.sv', '`include "x.svh"\n`include "x.svh"\n')
        self.write('x.svh', '`ifndef X\n`define X\nBODY\n`endif\n')
        result = self.merge([a], strip_comments=True)
        self.assertEqual(result.count('BODY'), 1)
        self.assertNotIn('guard already defined', result)

    def test_cli_flag_round_trip(self):
        src = self.write('top.sv', '// gone\nmodule m; endmodule\n')
        flist = self.write('run.f', src + '\n')
        rc = self.cli('-f', flist, '-o', str(self.output), '--strip-comments')
        self.assertEqual(rc, 0)
        text = self.output.read_text()
        self.assertNotIn('gone', text)
        self.assertIn('module m;', text)
        # No comment markers left anywhere in the file.
        self.assertNotIn('//', text)
        self.assertNotIn('/*', text)


if __name__ == '__main__':
    unittest.main()
