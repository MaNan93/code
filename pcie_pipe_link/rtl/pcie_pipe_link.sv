module pcie_pipe_link #(
    parameter int NL             = 4,
    parameter int DATA_WD        = 80,
    parameter int TXEI_WD        = 4,
    parameter int DIRFEEDBACK_WD = 12,
    parameter int FOMFEEDBACK_WD = 8,
    parameter int TX_COEF_WD     = 18,
    parameter int TX_PSET_WD     = 6,
    parameter int FS_LF_WD       = 6,
    parameter int RX_PSET_WD     = 3,
    parameter int PCLK_RATE_WD   = 5,
    parameter logic [2:0] MAX_RATE = 3'd5,
    parameter int ACK_CYCLES     = 8,
    parameter int EQ_CYCLES      = 8,
    parameter int FIFO_DEPTH     = 8
) (
    // Continuous reference clocks (one set for PHY clock switches)
    input  logic                        pclk_62p5,
    input  logic                        pclk_125,
    input  logic                        pclk_250,
    input  logic                        pclk_500,
    input  logic                        pclk_1000,

    // Per-lane link alignment status
    output logic [NL-1:0]               clocks_aligned,

    // =========================================================================
    // Downstream Port (DSP) Interface - All signals defined per-lane
    // =========================================================================
    input  logic [NL-1:0]               dsp_phy_rst_n,
    input  logic [NL-1:0]               dsp_pclk,
    input  logic [NL-1:0]               dsp_mac_phy_maxpclkreq_n,
    output logic [NL-1:0]               dsp_max_pclk,
    output logic [NL-1:0]               dsp_rx_clk,
    output logic [NL-1:0]               dsp_phy_mac_maxpclkack_n,
    output logic [NL-1:0]               dsp_phy_ref_clk_req_n,
    output logic [NL*3-1:0]             dsp_active_rate,
    output logic [NL-1:0]               dsp_clock_ready,

    input  logic [NL*3-1:0]             dsp_mac_phy_rate,
    input  logic [NL*4-1:0]             dsp_mac_phy_powerdown,
    input  logic [NL-1:0]               dsp_mac_phy_asyncpowerchangeack,
    input  logic [NL*PCLK_RATE_WD-1:0]  dsp_mac_phy_pclk_rate,
    input  logic [NL-1:0]               dsp_mac_phy_serdes_arch,
    input  logic [NL*2-1:0]             dsp_mac_phy_width,
    input  logic [NL*2-1:0]             dsp_mac_phy_rxwidth,

    input  logic [NL*DATA_WD-1:0]       dsp_mac_phy_txdata,
    input  logic [NL*TXEI_WD-1:0]       dsp_mac_phy_txelecidle,
    input  logic [NL-1:0]               dsp_mac_phy_txdatavalid,
    input  logic [NL-1:0]               dsp_mac_phy_txdetectrx_loopback,
    input  logic [NL-1:0]               dsp_mac_phy_rxstandby,
    input  logic [NL-1:0]               dsp_mac_phy_rxpolarity,
    input  logic [NL-1:0]               dsp_serdes_pipe_rxready,
    input  logic [NL-1:0]               dsp_serdes_pipe_turnoff_lanes,

    input  logic [NL-1:0]               dsp_mac_phy_rxeqeval,
    input  logic [NL-1:0]               dsp_mac_phy_rxeqinprogress,
    input  logic [NL-1:0]               dsp_mac_phy_invalid_req,
    input  logic [NL-1:0]               dsp_mac_phy_getlocal_pset_coef,
    input  logic [NL*TX_PSET_WD-1:0]    dsp_mac_phy_local_pset_index,
    input  logic [NL-1:0]               dsp_mac_phy_dirchange,
    input  logic [NL*TX_COEF_WD-1:0]    dsp_mac_phy_txdeemph,
    input  logic [NL*FS_LF_WD-1:0]      dsp_mac_phy_fs,
    input  logic [NL*FS_LF_WD-1:0]      dsp_mac_phy_lf,
    input  logic [NL*RX_PSET_WD-1:0]    dsp_mac_phy_rxpresethint,
    input  logic [NL*3-1:0]             dsp_mac_phy_txmargin,
    input  logic [NL-1:0]               dsp_mac_phy_txswing,
    input  logic [NL*8-1:0]             dsp_mac_phy_messagebus,
    input  logic [NL*32-1:0]            dsp_mac_phy_pipe_config_control,

    output logic [NL*DATA_WD-1:0]       dsp_phy_mac_rxdata,
    output logic [NL-1:0]               dsp_phy_mac_rxvalid,
    output logic [NL*3-1:0]             dsp_phy_mac_rxstatus,
    output logic [NL-1:0]               dsp_phy_mac_rxelecidle,
    output logic [NL-1:0]               dsp_phy_mac_rxstandbystatus,
    output logic [NL-1:0]               dsp_phy_mac_phystatus,
    output logic [NL*FS_LF_WD-1:0]      dsp_phy_mac_localfs,
    output logic [NL*FS_LF_WD-1:0]      dsp_phy_mac_locallf,
    output logic [NL*DIRFEEDBACK_WD-1:0] dsp_phy_mac_dirfeedback,
    output logic [NL*FOMFEEDBACK_WD-1:0] dsp_phy_mac_fomfeedback,
    output logic [NL*TX_COEF_WD-1:0]    dsp_phy_mac_local_tx_pset_coef,
    output logic [NL-1:0]               dsp_phy_mac_local_tx_coef_valid,
    output logic [NL*8-1:0]             dsp_phy_mac_messagebus,
    output logic [NL*32-1:0]            dsp_phy_mac_pipe_config_status,

    // =========================================================================
    // Upstream Port (USP) Interface - All signals defined per-lane
    // =========================================================================
    input  logic [NL-1:0]               usp_phy_rst_n,
    input  logic [NL-1:0]               usp_pclk,
    input  logic [NL-1:0]               usp_mac_phy_maxpclkreq_n,
    output logic [NL-1:0]               usp_max_pclk,
    output logic [NL-1:0]               usp_rx_clk,
    output logic [NL-1:0]               usp_phy_mac_maxpclkack_n,
    output logic [NL-1:0]               usp_phy_ref_clk_req_n,
    output logic [NL*3-1:0]             usp_active_rate,
    output logic [NL-1:0]               usp_clock_ready,

    input  logic [NL*3-1:0]             usp_mac_phy_rate,
    input  logic [NL*4-1:0]             usp_mac_phy_powerdown,
    input  logic [NL-1:0]               usp_mac_phy_asyncpowerchangeack,
    input  logic [NL*PCLK_RATE_WD-1:0]  usp_mac_phy_pclk_rate,
    input  logic [NL-1:0]               usp_mac_phy_serdes_arch,
    input  logic [NL*2-1:0]             usp_mac_phy_width,
    input  logic [NL*2-1:0]             usp_mac_phy_rxwidth,

    input  logic [NL*DATA_WD-1:0]       usp_mac_phy_txdata,
    input  logic [NL*TXEI_WD-1:0]       usp_mac_phy_txelecidle,
    input  logic [NL-1:0]               usp_mac_phy_txdatavalid,
    input  logic [NL-1:0]               usp_mac_phy_txdetectrx_loopback,
    input  logic [NL-1:0]               usp_mac_phy_rxstandby,
    input  logic [NL-1:0]               usp_mac_phy_rxpolarity,
    input  logic [NL-1:0]               usp_serdes_pipe_rxready,
    input  logic [NL-1:0]               usp_serdes_pipe_turnoff_lanes,

    input  logic [NL-1:0]               usp_mac_phy_rxeqeval,
    input  logic [NL-1:0]               usp_mac_phy_rxeqinprogress,
    input  logic [NL-1:0]               usp_mac_phy_invalid_req,
    input  logic [NL-1:0]               usp_mac_phy_getlocal_pset_coef,
    input  logic [NL*TX_PSET_WD-1:0]    usp_mac_phy_local_pset_index,
    input  logic [NL-1:0]               usp_mac_phy_dirchange,
    input  logic [NL*TX_COEF_WD-1:0]    usp_mac_phy_txdeemph,
    input  logic [NL*FS_LF_WD-1:0]      usp_mac_phy_fs,
    input  logic [NL*FS_LF_WD-1:0]      usp_mac_phy_lf,
    input  logic [NL*RX_PSET_WD-1:0]    usp_mac_phy_rxpresethint,
    input  logic [NL*3-1:0]             usp_mac_phy_txmargin,
    input  logic [NL-1:0]               usp_mac_phy_txswing,
    input  logic [NL*8-1:0]             usp_mac_phy_messagebus,
    input  logic [NL*32-1:0]            usp_mac_phy_pipe_config_control,

    output logic [NL*DATA_WD-1:0]       usp_phy_mac_rxdata,
    output logic [NL-1:0]               usp_phy_mac_rxvalid,
    output logic [NL*3-1:0]             usp_phy_mac_rxstatus,
    output logic [NL-1:0]               usp_phy_mac_rxelecidle,
    output logic [NL-1:0]               usp_phy_mac_rxstandbystatus,
    output logic [NL-1:0]               usp_phy_mac_phystatus,
    output logic [NL*FS_LF_WD-1:0]      usp_phy_mac_localfs,
    output logic [NL*FS_LF_WD-1:0]      usp_phy_mac_locallf,
    output logic [NL*DIRFEEDBACK_WD-1:0] usp_phy_mac_dirfeedback,
    output logic [NL*FOMFEEDBACK_WD-1:0] usp_phy_mac_fomfeedback,
    output logic [NL*TX_COEF_WD-1:0]    usp_phy_mac_local_tx_pset_coef,
    output logic [NL-1:0]               usp_phy_mac_local_tx_coef_valid,
    output logic [NL*8-1:0]             usp_phy_mac_messagebus,
    output logic [NL*32-1:0]            usp_phy_mac_pipe_config_status
);
    logic [NL*3-1:0] dsp_lane_rxstatus;
    logic [NL*3-1:0] usp_lane_rxstatus;

    assign dsp_lane_rxstatus = '0;
    assign usp_lane_rxstatus = '0;

    for (genvar i = 0; i < NL; i++) begin : g_link_lane
        assign clocks_aligned[i] = dsp_phy_rst_n[i] && usp_phy_rst_n[i] &&
                                   dsp_clock_ready[i] && usp_clock_ready[i] &&
                                   (dsp_active_rate[i*3 +: 3] == usp_active_rate[i*3 +: 3]);

        pcie_pipe_lane #(
            .DATA_WD   (DATA_WD),
            .TXEI_WD   (TXEI_WD),
            .FIFO_DEPTH(FIFO_DEPTH)
        ) u_lane (
            .dsp_pclk        (dsp_pclk[i]),
            .dsp_rx_clk      (dsp_rx_clk[i]),
            .dsp_phy_rst_n   (dsp_phy_rst_n[i]),
            .usp_pclk        (usp_pclk[i]),
            .usp_rx_clk      (usp_rx_clk[i]),
            .usp_phy_rst_n   (usp_phy_rst_n[i]),
            .clocks_aligned  (clocks_aligned[i]),
            .dsp_powerdown   (dsp_mac_phy_powerdown[i*4 +: 4]),
            .dsp_rxpolarity  (dsp_mac_phy_rxpolarity[i]),
            .dsp_txelecidle  (dsp_mac_phy_txelecidle[i*TXEI_WD +: TXEI_WD]),
            .dsp_txdatavalid (dsp_mac_phy_txdatavalid[i]),
            .dsp_txdata      (dsp_mac_phy_txdata[i*DATA_WD +: DATA_WD]),
            .dsp_turnoff_lane(dsp_serdes_pipe_turnoff_lanes[i]),
            .usp_powerdown   (usp_mac_phy_powerdown[i*4 +: 4]),
            .usp_rxpolarity  (usp_mac_phy_rxpolarity[i]),
            .usp_txelecidle  (usp_mac_phy_txelecidle[i*TXEI_WD +: TXEI_WD]),
            .usp_txdatavalid (usp_mac_phy_txdatavalid[i]),
            .usp_txdata      (usp_mac_phy_txdata[i*DATA_WD +: DATA_WD]),
            .usp_turnoff_lane(usp_serdes_pipe_turnoff_lanes[i]),
            .dsp_rxdata      (dsp_phy_mac_rxdata[i*DATA_WD +: DATA_WD]),
            .dsp_rxvalid     (dsp_phy_mac_rxvalid[i]),
            .dsp_rxelecidle  (dsp_phy_mac_rxelecidle[i]),
            .usp_rxdata      (usp_phy_mac_rxdata[i*DATA_WD +: DATA_WD]),
            .usp_rxvalid     (usp_phy_mac_rxvalid[i]),
            .usp_rxelecidle  (usp_phy_mac_rxelecidle[i])
        );
    end

    pcie_pipe_side #(
        .NL            (NL),
        .DATA_WD       (DATA_WD),
        .TXEI_WD       (TXEI_WD),
        .DIRFEEDBACK_WD(DIRFEEDBACK_WD),
        .FOMFEEDBACK_WD(FOMFEEDBACK_WD),
        .TX_COEF_WD    (TX_COEF_WD),
        .TX_PSET_WD    (TX_PSET_WD),
        .FS_LF_WD      (FS_LF_WD),
        .RX_PSET_WD    (RX_PSET_WD),
        .PCLK_RATE_WD  (PCLK_RATE_WD),
        .MAX_RATE      (MAX_RATE),
        .ACK_CYCLES    (ACK_CYCLES),
        .EQ_CYCLES     (EQ_CYCLES)
    ) u_dsp_side (
        .pclk_62p5                  (pclk_62p5),
        .pclk_125                   (pclk_125),
        .pclk_250                   (pclk_250),
        .pclk_500                   (pclk_500),
        .pclk_1000                  (pclk_1000),
        .phy_rst_n                  (dsp_phy_rst_n),
        .pclk                       (dsp_pclk),
        .mac_phy_maxpclkreq_n       (dsp_mac_phy_maxpclkreq_n),
        .peer_active_rate           (usp_active_rate),
        .peer_phy_rst_n             (usp_phy_rst_n),
        .max_pclk                   (dsp_max_pclk),
        .rx_clk                     (dsp_rx_clk),
        .phy_mac_maxpclkack_n       (dsp_phy_mac_maxpclkack_n),
        .phy_ref_clk_req_n          (dsp_phy_ref_clk_req_n),
        .active_rate                (dsp_active_rate),
        .clock_ready                (dsp_clock_ready),
        .mac_phy_rate               (dsp_mac_phy_rate),
        .mac_phy_powerdown          (dsp_mac_phy_powerdown),
        .mac_phy_asyncpowerchangeack(dsp_mac_phy_asyncpowerchangeack),
        .mac_phy_pclk_rate          (dsp_mac_phy_pclk_rate),
        .mac_phy_serdes_arch        (dsp_mac_phy_serdes_arch),
        .mac_phy_width              (dsp_mac_phy_width),
        .mac_phy_rxwidth            (dsp_mac_phy_rxwidth),
        .mac_phy_txelecidle         (dsp_mac_phy_txelecidle),
        .mac_phy_txdetectrx_loopback(dsp_mac_phy_txdetectrx_loopback),
        .mac_phy_rxstandby          (dsp_mac_phy_rxstandby),
        .serdes_pipe_rxready        (dsp_serdes_pipe_rxready),
        .serdes_pipe_turnoff_lanes  (dsp_serdes_pipe_turnoff_lanes),
        .mac_phy_rxeqeval           (dsp_mac_phy_rxeqeval),
        .mac_phy_rxeqinprogress     (dsp_mac_phy_rxeqinprogress),
        .mac_phy_invalid_req        (dsp_mac_phy_invalid_req),
        .mac_phy_getlocal_pset_coef (dsp_mac_phy_getlocal_pset_coef),
        .mac_phy_local_pset_index   (dsp_mac_phy_local_pset_index),
        .mac_phy_dirchange          (dsp_mac_phy_dirchange),
        .mac_phy_txdeemph           (dsp_mac_phy_txdeemph),
        .mac_phy_fs                 (dsp_mac_phy_fs),
        .mac_phy_lf                 (dsp_mac_phy_lf),
        .mac_phy_rxpresethint       (dsp_mac_phy_rxpresethint),
        .mac_phy_txmargin           (dsp_mac_phy_txmargin),
        .mac_phy_txswing            (dsp_mac_phy_txswing),
        .mac_phy_messagebus         (dsp_mac_phy_messagebus),
        .mac_phy_pipe_config_control(dsp_mac_phy_pipe_config_control),
        .phy_mac_rxstandbystatus    (dsp_phy_mac_rxstandbystatus),
        .phy_mac_phystatus          (dsp_phy_mac_phystatus),
        .phy_mac_localfs            (dsp_phy_mac_localfs),
        .phy_mac_locallf            (dsp_phy_mac_locallf),
        .phy_mac_dirfeedback        (dsp_phy_mac_dirfeedback),
        .phy_mac_fomfeedback        (dsp_phy_mac_fomfeedback),
        .phy_mac_local_tx_pset_coef (dsp_phy_mac_local_tx_pset_coef),
        .phy_mac_local_tx_coef_valid(dsp_phy_mac_local_tx_coef_valid),
        .phy_mac_messagebus         (dsp_phy_mac_messagebus),
        .phy_mac_pipe_config_status (dsp_phy_mac_pipe_config_status),
        .lane_rxstatus_in           (dsp_lane_rxstatus),
        .phy_mac_rxstatus           (dsp_phy_mac_rxstatus)
    );

    pcie_pipe_side #(
        .NL            (NL),
        .DATA_WD       (DATA_WD),
        .TXEI_WD       (TXEI_WD),
        .DIRFEEDBACK_WD(DIRFEEDBACK_WD),
        .FOMFEEDBACK_WD(FOMFEEDBACK_WD),
        .TX_COEF_WD    (TX_COEF_WD),
        .TX_PSET_WD    (TX_PSET_WD),
        .FS_LF_WD      (FS_LF_WD),
        .RX_PSET_WD    (RX_PSET_WD),
        .PCLK_RATE_WD  (PCLK_RATE_WD),
        .MAX_RATE      (MAX_RATE),
        .ACK_CYCLES    (ACK_CYCLES),
        .EQ_CYCLES     (EQ_CYCLES)
    ) u_usp_side (
        .pclk_62p5                  (pclk_62p5),
        .pclk_125                   (pclk_125),
        .pclk_250                   (pclk_250),
        .pclk_500                   (pclk_500),
        .pclk_1000                  (pclk_1000),
        .phy_rst_n                  (usp_phy_rst_n),
        .pclk                       (usp_pclk),
        .mac_phy_maxpclkreq_n       (usp_mac_phy_maxpclkreq_n),
        .peer_active_rate           (dsp_active_rate),
        .peer_phy_rst_n             (dsp_phy_rst_n),
        .max_pclk                   (usp_max_pclk),
        .rx_clk                     (usp_rx_clk),
        .phy_mac_maxpclkack_n       (usp_phy_mac_maxpclkack_n),
        .phy_ref_clk_req_n          (usp_phy_ref_clk_req_n),
        .active_rate                (usp_active_rate),
        .clock_ready                (usp_clock_ready),
        .mac_phy_rate               (usp_mac_phy_rate),
        .mac_phy_powerdown          (usp_mac_phy_powerdown),
        .mac_phy_asyncpowerchangeack(usp_mac_phy_asyncpowerchangeack),
        .mac_phy_pclk_rate          (usp_mac_phy_pclk_rate),
        .mac_phy_serdes_arch        (usp_mac_phy_serdes_arch),
        .mac_phy_width              (usp_mac_phy_width),
        .mac_phy_rxwidth            (usp_mac_phy_rxwidth),
        .mac_phy_txelecidle         (usp_mac_phy_txelecidle),
        .mac_phy_txdetectrx_loopback(usp_mac_phy_txdetectrx_loopback),
        .mac_phy_rxstandby          (usp_mac_phy_rxstandby),
        .serdes_pipe_rxready        (usp_serdes_pipe_rxready),
        .serdes_pipe_turnoff_lanes  (usp_serdes_pipe_turnoff_lanes),
        .mac_phy_rxeqeval           (usp_mac_phy_rxeqeval),
        .mac_phy_rxeqinprogress     (usp_mac_phy_rxeqinprogress),
        .mac_phy_invalid_req        (usp_mac_phy_invalid_req),
        .mac_phy_getlocal_pset_coef (usp_mac_phy_getlocal_pset_coef),
        .mac_phy_local_pset_index   (usp_mac_phy_local_pset_index),
        .mac_phy_dirchange          (usp_mac_phy_dirchange),
        .mac_phy_txdeemph           (usp_mac_phy_txdeemph),
        .mac_phy_fs                 (usp_mac_phy_fs),
        .mac_phy_lf                 (usp_mac_phy_lf),
        .mac_phy_rxpresethint       (usp_mac_phy_rxpresethint),
        .mac_phy_txmargin           (usp_mac_phy_txmargin),
        .mac_phy_txswing            (usp_mac_phy_txswing),
        .mac_phy_messagebus         (usp_mac_phy_messagebus),
        .mac_phy_pipe_config_control(usp_mac_phy_pipe_config_control),
        .phy_mac_rxstandbystatus    (usp_phy_mac_rxstandbystatus),
        .phy_mac_phystatus          (usp_phy_mac_phystatus),
        .phy_mac_localfs            (usp_phy_mac_localfs),
        .phy_mac_locallf            (usp_phy_mac_locallf),
        .phy_mac_dirfeedback        (usp_phy_mac_dirfeedback),
        .phy_mac_fomfeedback        (usp_phy_mac_fomfeedback),
        .phy_mac_local_tx_pset_coef (usp_phy_mac_local_tx_pset_coef),
        .phy_mac_local_tx_coef_valid(usp_phy_mac_local_tx_coef_valid),
        .phy_mac_messagebus         (usp_phy_mac_messagebus),
        .phy_mac_pipe_config_status (usp_phy_mac_pipe_config_status),
        .lane_rxstatus_in           (usp_lane_rxstatus),
        .phy_mac_rxstatus           (usp_phy_mac_rxstatus)
    );
endmodule
