// The Receiver can implement a majority voting to correct these fields
//   If two sets of value are 0b and two sets are 1b, there is a tie. 
//     A tie in the parity can be considered to mismatch.
function automatic [1:0] f_vote_parity_bit;
    input [3:0] parity_bit;
    reg         vote_invalid;
    reg         vote_parity_bit;
    begin
        vote_invalid    = 1'b1;
        vote_parity_bit = 1'b0;

       if(((parity_bit[2] == parity_bit[1]) && (parity_bit[1] == parity_bit[0]))
       || ((parity_bit[3] == parity_bit[1]) && (parity_bit[1] == parity_bit[0]))
       || ((parity_bit[3] == parity_bit[2]) && (parity_bit[2] == parity_bit[0]))
       ) begin
           vote_invalid    = 1'b0;
           vote_parity_bit = parity_bit[0];
       end else if((parity_bit[3] == parity_bit[2]) && (parity_bit[2] == parity_bit[1])) begin
           vote_invalid    = 1'b0;
           vote_parity_bit = parity_bit[1];
       end
       f_vote_parity_bit = {vote_invalid,vote_parity_bit};
    end
endfunction // enuf
