    if ( !core_rst_n ) begin
        latched_skp_end <= #TP 0;
    end else begin
        if (int_skp_end)
            latched_skp_end <= #TP 1;
        else if (!rxdata_skip[0])
            latched_skp_end <= #TP 0;
    end
end

