   function automatic [NB-1:0] shift_bit;
   input [NB-1:0] data;
   input [NB-1:0] shift_data;
   input [AW-1:0] active_nb;
   begin
                   // 1s mode
      shift_bit = (active_nb[0]) ?  {{NB-1{1'b0}}, data[0]} :
                   // 2s mode
                  (active_nb[1]) ? (shift_data[0] ? {{NB-2{1'b0}}, data[1:0]} : {{NB-2{1'b0}}, data[0], data[1]}) :
                   // 4s mode    // first incoming data goes into fifo0
                  (active_nb[2]) ? ((shift_data[0] ? {{NB-4{1'b0}}, data[3], data[2], data[1], data[0]} : 16'd0)
                                 // first incoming data goes into fifo1
                                  | (shift_data[1] ? {{NB-4{1'b0}}, data[2], data[1], data[0], data[3]} : 16'd0)
                                 // first incoming data goes into fifo2
                                  | (shift_data[2] ? {{NB-4{1'b0}}, data[1], data[0], data[3], data[2]} : 16'd0)
                                 // first incoming data goes into fifo3
                                  | (shift_data[3] ? {{NB-4{1'b0}}, data[0], data[3], data[2], data[1]} : 16'd0))  :
                   // 8s/16s mode
                                    {NB{1'b0}} ; // Unused for Gen3 8s/16s
   end
   endfunction

   function automatic [NB*8-1:0] shift_word;
   input [NB*8-1:0] data;
   input [NB-1:0]   shift_data;
   input [AW-1:0]   active_nb;
   begin
                   // 1s mode
      shift_word = (active_nb[0]) ? {{(NB-1)*8{1'b0}}, data[7:0]} :
                   // 2s mode
                   (active_nb[1]) ? (shift_data[0] ? {{(NB-2)*8{1'b0}}, data[15:0]} : {{(NB-2)*8{1'b0}}, data[7:0], data[15:8]}) :
                   // 4s mode
                  (active_nb[2]) ? ((shift_data[0] ? {{(NB-4)*8{1'b0}}, data[31:24], data[23:16], data[15:8],  data[7:0]}   : {NB*8{1'b0}})
                                 // first incoming data goes into fifo1
                                  | (shift_data[1] ? {{(NB-4)*8{1'b0}}, data[23:16], data[15:8],  data[7:0],   data[31:24]} : {NB*8{1'b0}})
                                 // first incoming data goes into fifo2
                                  | (shift_data[2] ? {{(NB-4)*8{1'b0}}, data[15:8],  data[7:0],   data[31:24], data[23:16]} : {NB*8{1'b0}})
                                 // first incoming data goes into fifo3
                                  | (shift_data[3] ? {{(NB-4)*8{1'b0}}, data[7:0],   data[31:24], data[23:16], data[15:8]}  : {NB*8{1'b0}})) :
                   // 8s mode
                                    {NB*8{1'b0}};  // Unused for Gen3 8s
   end
   endfunction

