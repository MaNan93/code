// function to count bits
function automatic [7:0] cal_assert_bit;
input [NB-1:0] req;
reg [7:0] cnt;
integer   m;
begin
    cnt = 0;
    for(m=0; m<NB; m=m+1) begin
        if(req[m]) begin
            cnt = cnt + 1;
        end
    end
    cal_assert_bit = cnt;
end
