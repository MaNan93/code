// rxdata_dv = rxdatavalid & rxaligned, rxaligned = rxvalid. For nominal empty buffer mode, rxdatavalid can be 0 for long time. cfg_elastic_buffer_mode = 0, half full mode
// But if rxvalid = 0 after rxstartblock = 1, have to push 16 symbols to buffer for pop side to get block_cnt = 16. This can occur in Loopback Master. rxvalid = 0 cannot be only for a few cycles.
assign rxdata_dv_deassert_cnt_bigger2 = (( (~rxdata_dv && (rxdata_dv_deassert_cnt == 2)) || (rxdata_dv_deassert_cnt == 3) ) & ~cfg_elastic_buffer_mode) | (~rxaligned && (rxdata_dv_deassert_cnt >= 1) && cfg_elastic_buffer_mode);

//generate block_cnt
always @(posedge core_clk or negedge core_rst_n) begin : block_cnt_seq_PROC
    if( !core_rst_n ) begin
        block_cnt <= #TP 15;
    end else begin
        if ( !deskew_enable ) //no count if !deskew_enable
            block_cnt <= #TP 16 - int_active_nb;
        else if ( rxdata_dv && rxstartblock[0] && deskew_enable && rxdata_skip[0] ) // SKP Block Sym number can be variable (8,12,16,20,24)
            block_cnt <= #TP 16 - int_active_nb;
        else if ( (block_cnt == (16 - int_active_nb)) && rxdata_dv && rxstartblock[0] && deskew_enable ) begin // when receiving early/late startblock make sure we write always a full 16-byte block
            block_cnt <= #TP 0;
        end else if ( (block_cnt < (16 - int_active_nb)) && deskew_enable && (rxdata_dv || rxdata_dv_deassert_cnt_bigger2) ) begin
// spyglass disable_block W164a
// SMD: Identifies assignments in which the LHS width is less than the RHS width
// SJ: The rule reports assignments where the result of an addition or subtraction operation is being assigned to a bus of the same width as the operands of the addition or subtraction operation. In this code, the carry or borrow bit is considered and isn't lost. So, disable SpyGlass from reporting this warning.
            block_cnt <= #TP block_cnt + int_active_nb;
// spyglass enable_block W164a
        end
    end
end // block_cnt_seq_PROC
assign load_g3 = (rxdata_dv || rxdata_dv_deassert_cnt_bigger2) && ( rxstartblock[0] || ((block_cnt < (16 - int_active_nb)) && !rxdata_skip[0])); // assume rxdata_skip is active during entire skp os

//squelch the data and valid to pkt_finder if ~deskew_enable
//skp_do_deskew is a combinatorial logic to detect SKIP OS. And deskew_enable = skp_do_deskew | ...
//So if skp_do_deskew = 1, deskew_enable = 1 at the same cycle to not squelch data at the same cycle, too
assign squelch = ~deskew_enable /* | deskew_see_idl_os */ ;
// FIFO Read Side Logic
assign deskew_rxdata_dv   =
                            //need !empty[0] as data not valid if fifo is empty & just need empty[0] because it is a block for gen3 rate.
                            //So if [0] !empty, then the other active symbols !empty
                            (current_data_rate == `GEN3_RATE || current_data_rate == `GEN4_RATE || current_data_rate == `GEN5_RATE || current_data_rate == `GEN6_RATE) ? ((!deskew_framing_err | cdm_ras_des_ferr_rec_dis) & deskew_unload_g3 & !empty[0] & ~deskew_skpos_first_cycle) :
                            (deskew_rxdata_dv_i & !int_deskew_see_idl_os & ~squelch & ~deskew_flit_eios_det_g12 & ~l0p_g12_realign_point) | extra_k_sris_flag;
assign deskew_rxdata      = extra_k_sris_flag ? {(NB*8){1'b0}} : (current_data_rate == `GEN1_RATE || current_data_rate == `GEN2_RATE) & squelch ? 0 : deskew_rxdata_i;
assign deskew_rxdatak     = extra_k_sris_flag ? bit_kchar      : (current_data_rate == `GEN1_RATE || current_data_rate == `GEN2_RATE) & squelch ? 0 : deskew_rxdatak_i[NB-1:0];
assign deskew_rxerror     = (current_data_rate == `GEN1_RATE || current_data_rate == `GEN2_RATE) & squelch ? 0 : deskew_rxerror_i[NB-1:0];
assign deskew_overflow    = deskew_overflow_i;

   // we are ready with data when all active fifos have at least one word in them
assign deskew_rxdata_dv_i = &(
                              active_nb[3] ? ~empty[7:0] :  // 8s
                              active_nb[2] ? ~empty[3:0] :  // 4s
                              active_nb[1] ? ~empty[1:0] :  // 2s
                                             ~empty[0]      // 1s
                              );

// when in the the upper S mode, then use the almost_full signal
assign active_full = (active_nb != `CX_NB_GEN1) ? almost_full : full;

   always @(posedge core_clk or negedge core_rst_n)
     if (~core_rst_n)
         deskew_overflow_i  <= #TP 1'b0;
     else
         deskew_overflow_i  <= #TP
                                 ( current_data_rate == `GEN3_RATE || current_data_rate == `GEN4_RATE || current_data_rate == `GEN5_RATE || current_data_rate == `GEN6_RATE) ? |(active_full & shift_load) :
                                   deskew_bypass ? 0 : |(active_full & shift_load) | ts_state[ALIGN_ERROR]; // if bypass FIFO, no overflow

assign skip_out         = {
                           {NB-4{1'b0}},
                           (deskew_rxdatak_i[3] & (deskew_rxdata_i[31:24] == `SKIP_8B)),
                           (deskew_rxdatak_i[2] & (deskew_rxdata_i[23:16] == `SKIP_8B)),

                           (deskew_rxdatak_i[1] & (deskew_rxdata_i[15:8] == `SKIP_8B)),

                           (deskew_rxdatak_i[0] & (deskew_rxdata_i[7:0]  == `SKIP_8B))};

   // a single SKP symbol per SKP ordered set is used as alignment
   // markers on the output of the deskew block
assign deskew_skp       = skip_out;

// FIFO Write Side Logic
   wire [NB-1:0] write_rxword;
   wire [NB-1:0] write_rxword_unmask;     // this word needs to be written into a fifo, one bit per byte, based on rxdata
   wire [NB-1:0] write_rxword_unmask_nfm; // non-flit mode: this word needs to be written into a fifo, one bit per byte, based on rxdata
   wire [NB-1:0] write_rxword_unmask_fm;  // jd6 flit mode: do not write any SKP into fifo for flit mode. each flit has CRC to check incorrectness and the flit will replay if wrong

// the original deskew logic did not depend on rxdata_dv
// from the pipe interface, data just flowed through
//
// because of this we don't have to worry about squelch
// cases where the end of a packet isn't loaded even though
// it should be

// assign            int_rxdata_dv = rxdata_dv;
wire            int_rxdata_dv;
assign           int_rxdata_dv = (cfg_elastic_buffer_mode || smlh_flit_mode_enable) ? rxdata_dv : 1'b1;


logic [NB-1:0]        radata_com_followed_by_skp ;          // COM symbol that if followed by SKP OS(SKP symbol or Bare com) if this com is for SKP symbol all SKP symbols are masked.
logic                 prev_com_followed_by_skp_reg ; 
logic [NB-1:0]        msk_nfm_for_com_followed_by_skp ;     // Masking write_rxword_unmask_nfm for radata_com_followed_by_skp

always_comb begin
    radata_com_followed_by_skp      = '0 ;
    msk_nfm_for_com_followed_by_skp = '0 ;
    
    if( active_nb[2] ) begin
        radata_com_followed_by_skp[3] = rxdata_comma[3] & ( rxdata_skprm[2] | rxdata_skip[2] ) ;
        radata_com_followed_by_skp[2] = rxdata_comma[2] & ( rxdata_skprm[1] | rxdata_skip[1] ) ;
    end
    if( active_nb[1] ) begin
        radata_com_followed_by_skp[1] = rxdata_comma[1] & ( rxdata_skprm[0] | rxdata_skip[0] ) ;
    end
        radata_com_followed_by_skp[0] = rxdata_comma[0] & ( prev_skprm_reg  | prev_skp_reg ) ;


    if( active_nb[2] ) begin
        msk_nfm_for_com_followed_by_skp[3] = radata_com_followed_by_skp[2] & ( rxdata_skprm[3] | rxdata_skip[3] ) ;
        msk_nfm_for_com_followed_by_skp[2] = radata_com_followed_by_skp[1] & ( rxdata_skprm[2] | rxdata_skip[2] ) ;
    end
    if( active_nb[1] ) begin
        msk_nfm_for_com_followed_by_skp[1] = radata_com_followed_by_skp[0] & ( rxdata_skprm[1] | rxdata_skip[1] ) ;
    end
        msk_nfm_for_com_followed_by_skp[0] = prev_com_followed_by_skp_reg  & ( rxdata_skprm[0] | rxdata_skip[0] ) ;
end

// Control masking of data into the FIFOs. We only write 1 SKP character per SKP ordered set
// i.e. only the SKP that immediately follows the COM. Don't push COM because a bare COM for SKP OS is converted to SKP symbol which is used to push

assign write_rxword_unmask_nfm =  {NB{int_rxdata_dv}}
                     & {
                           {NB-4{1'b0}},
                       active_nb[2] & ( msk_nfm_for_com_followed_by_skp[3] ? 1'b0 : rxdata_skprm[3] ? 1'b1 : rxdata_comma[3] ? 1'b0 : (rxdata_skprm[2] & rxdata_skip[3]) ? 1'b0 : (
                           rxdata_comma[2]
                        | ~rxdata_comma[2] & ~rxdata_skip[3]) ),

                       active_nb[2] & ( msk_nfm_for_com_followed_by_skp[2] ? 1'b0 : rxdata_skprm[2] ? 1'b1 : rxdata_comma[2] ? 1'b0 : (rxdata_skprm[1] & rxdata_skip[2]) ? 1'b0 : (
                           rxdata_comma[1]
                        | ~rxdata_comma[1] & ~rxdata_skip[2]) ),

                      (|active_nb[2:1]) & ( msk_nfm_for_com_followed_by_skp[1] ? 1'b0 : rxdata_skprm[1] ? 1'b1 : rxdata_comma[1] ? 1'b0 : (rxdata_skprm[0] & rxdata_skip[1]) ? 1'b0 : (
                           rxdata_comma[0]
                        | ~rxdata_comma[0] & ~rxdata_skip[1]) ),

                           msk_nfm_for_com_followed_by_skp[0] ? 1'b0 : rxdata_skprm[0] ? 1'b1 : rxdata_comma[0] ? 1'b0 : (prev_skprm_reg & rxdata_skip[0]) ? 1'b0 : (  // COM & skprm, push; COM, no push; previous-skprm & skip, no push
                           skp_do_deskew & ~skp_do_deskew_r & prev_com_reg & ~rxdata_skip[0] ? 1'b0 :  // skp lock point and ~SKP symbol, no push
                           prev_com_reg // previous-pure-COM, push regardless
                        | ~prev_com_reg & ~rxdata_skip[0]) }; // previous-not-COM & current-not-skip, push

assign write_rxword_unmask_fm =  {NB{int_rxdata_dv}}
                     & {
                           {NB-4{1'b0}},
                       active_nb[2] & ( rxdata_skprm[3] | rxdata_comma[3] | rxdata_skip[3] ? 1'b0 : (
                           rxdata_comma[2]
                        | ~rxdata_comma[2] & ~rxdata_skip[3]) ),

                       active_nb[2] & ( rxdata_skprm[2] | rxdata_comma[2] | rxdata_skip[2] ? 1'b0 : (
                           rxdata_comma[1]
                        | ~rxdata_comma[1] & ~rxdata_skip[2]) ),

                      (|active_nb[2:1]) & ( rxdata_skprm[1] | rxdata_comma[1] | rxdata_skip[1] ? 1'b0 : (
                           rxdata_comma[0]
                        | ~rxdata_comma[0] & ~rxdata_skip[1]) ),

                           rxdata_skprm[0] | rxdata_comma[0] | rxdata_skip[0] ? 1'b0 : (               // COM | skip, no push
                           skp_do_deskew & ~skp_do_deskew_r & prev_com_reg & ~rxdata_skip[0] ? 1'b0 :  // skp lock point and ~SKP symbol, no push
                           prev_com_reg // previous-pure-COM, push regardless
                        | ~prev_com_reg & ~rxdata_skip[0]) }; // previous-not-COM & current-not-skip, push

assign write_rxword_unmask = smlh_flit_mode_enable ? write_rxword_unmask_fm : write_rxword_unmask_nfm;

// signal an error if we see a SKP where the previous symbol is not a COM or a SKP
assign deskew_skp_alignment_err = ~int_rxdata_dv ? 0 :
                        (current_data_rate == `GEN3_RATE || current_data_rate == `GEN4_RATE || current_data_rate == `GEN5_RATE || current_data_rate == `GEN6_RATE) ? 0 :
                        (deskew_latched_l0p_ei_rcvd && ~(&l0p_rxaligned_cnt)) ? 0 : // Disable because first skp os is corrupted
                        active_nb[2] & (  ~rxdata_comma[2] & ~rxdata_skip[2]  & rxdata_skip[3] & ~rxdata_skprm[3] ) |
                        active_nb[2] & (  ~rxdata_comma[1] & ~rxdata_skip[1]  & rxdata_skip[2] & ~rxdata_skprm[2] ) |
                        (|active_nb[2:1]) & ( ~rxdata_comma[0] & ~rxdata_skip[0]  & rxdata_skip[1] & ~rxdata_skprm[1] ) |
                        ~prev_com_reg & ~prev_skp_reg & rxdata_skip[0] & ~rxdata_skprm[0];

// Identify when (and where) we are writing a SKP ordered set into the FIFOs.
// the core may have rxpolarity asserted in Polling.Active and invert SKIP symbols on some lanes. So no skip deskew lock in Polling.Active state.
assign skp_lock_point = cfg_ts2_lid_deskew ? // ts2/eieos/skp -> idle do deskew, needs SKP OS for deskew in L0/RxL0s/LoopbackMaster
                       (
                        (smlh_ltssm_state != S_POLL_ACTIVE && (ltssm_lpbk_master || smlh_in_rl0s || smlh_ltssm_state == S_L0)) & int_rxdata_dv & (
                      |{
                         active_nb[2]   & ( rxdata_skprm[3] ? 1'b1 :
                                           (rxdata_comma[2] & ~rxdata_skprm[2] & rxdata_skip[3]) ),
                         active_nb[2]   & ( rxdata_skprm[2] ? 1'b1 :
                                           (rxdata_comma[1] & ~rxdata_skprm[1] & rxdata_skip[2]) ),
                        |active_nb[2:1] & ( rxdata_skprm[1] ? 1'b1 :
                                           (rxdata_comma[0] & ~rxdata_skprm[0] & rxdata_skip[1]) ),
                          rxdata_skprm[0] ? 1'b1 :
                                            prev_com_reg & ~prev_skprm_reg & rxdata_skip[0]} )
                       ) :
                       (
                        (smlh_ltssm_state != S_POLL_ACTIVE) & int_rxdata_dv & (
                      |{
                         active_nb[2]   & ( rxdata_skprm[3] ? 1'b1 :
                                           (rxdata_comma[2] & ~rxdata_skprm[2] & rxdata_skip[3]) ),
                         active_nb[2]   & ( rxdata_skprm[2] ? 1'b1 :
                                           (rxdata_comma[1] & ~rxdata_skprm[1] & rxdata_skip[2]) ),
                        (|active_nb[2:1]) & ( rxdata_skprm[1] ? 1'b1 :
                                           (rxdata_comma[0] & ~rxdata_skprm[0] & rxdata_skip[1]) ),
                          rxdata_skprm[0] ? 1'b1 :
                                            prev_com_reg & ~prev_skprm_reg & rxdata_skip[0]} )
                       );

// Identify when (and where) we are modifying rxdatak to k-char and modifying rxdata to zero and push into the FIFOs.
// for current symbol, if previous sym is ~COM, no modifying.
// for current symbol, if previous sym is COM but skp_removal, no modifying. (may be bare com).
// for current symbol, if it is k-char, no modifying.
// so only when current sym is ~k-char AND previous sym is (COM && ~skp_removal), modifying current rxdatak to k-char and rxdata to zero.
// the logic is used for pkt_finder to receive TLP START but no TLP END, which can cause framing error because of receiving the k-char which is not TLP END
assign com_lock_point = {
                           {NB-4{1'b0}},
                         active_nb[2]   & ( rxdata_comma[2] & ~rxdata_skprm[2] & ~rxdatak[3] ),
                         active_nb[2]   & ( rxdata_comma[1] & ~rxdata_skprm[1] & ~rxdatak[2] ),
                        (|active_nb[2:1]) & ( rxdata_comma[0] & ~rxdata_skprm[0] & ~rxdatak[1] ),
                         prev_com_reg & ~prev_skprm_reg & ~rxdatak[0]
                        } & {NB{int_rxdata_dv}};

// if the SKP is used to enable deskew, we must suppress the k-char bytes before {SKIP, COM, xx, xx}
assign masked_rxdatak = ~int_rxdata_dv ? 0 :
                          active_nb[2] & ((rxdata_comma[1] & rxdata_skip[2])                  ) ? 8'b11111110 :
                          active_nb[2] & ((rxdata_comma[2] & rxdata_skip[3]) | rxdata_skprm[2]) ? 8'b11111100 :
                          active_nb[2] & (                                     rxdata_skprm[3]) ? 8'b11111000 :
                       (|active_nb[2:1]) & (                                   rxdata_skprm[1]) ? 8'b11111110 :
                          8'b11111111;
                        

//logic below is to detect EIOS
//deskew_rxdata_dv and deskew_complete are deasserted when detecting EIOS,
//not based on detecting a single EI Symbol
assign int_rxvalid = deskew_rxdata_dv_i;
assign int_rxdata  = deskew_rxdata_i;
assign int_rxdatak = deskew_rxdatak_i[NB-1:0];

//detect COM
assign comk = {
               active_nb[2]                & int_rxvalid & int_rxdatak[3] & (int_rxdata[31:24] == `COMMA_8B),
               active_nb[2]                & int_rxvalid & int_rxdatak[2] & (int_rxdata[23:16] == `COMMA_8B),
               (active_nb[2]|active_nb[1]) & int_rxvalid & int_rxdatak[1] & (int_rxdata[15:8]  == `COMMA_8B),
               |active_nb                  & int_rxvalid & int_rxdatak[0] & (int_rxdata[7:0]   == `COMMA_8B)
               };

//detect EIDLE Symbol
assign idlk = {
               active_nb[2]                & int_rxvalid & int_rxdatak[3] & (int_rxdata[31:24] == `EIDLE_8B),
               active_nb[2]                & int_rxvalid & int_rxdatak[2] & (int_rxdata[23:16] == `EIDLE_8B),
               (active_nb[2]|active_nb[1]) & int_rxvalid & int_rxdatak[1] & (int_rxdata[15:8]  == `EIDLE_8B),
               |active_nb                  & int_rxvalid & int_rxdatak[0] & (int_rxdata[7:0]   == `EIDLE_8B)
               };

//shift COM, dependent on active_nb
always @(posedge core_clk or negedge core_rst_n) begin : comkq_PROC
    if (~core_rst_n)
        comkq <= #TP 3'h0;
    else if (active_nb[2])  // 4s
        comkq <= #TP comk[3:1];
    else if (active_nb[1])  // 2s
        comkq <= #TP {comk[1:0], comkq[3]};
    else
        comkq <= #TP {comk[0], comkq[3:2]};
end

//shift EIDLE, dependent on active_nb
always @(posedge core_clk or negedge core_rst_n) begin : idlkq_PROC
    if (~core_rst_n)
        idlkq <= #TP 2'h0;
    else if (active_nb[2])  // 4s
        idlkq <= #TP idlk[3:2];
    else if (active_nb[1])  // 2s
        idlkq <= #TP idlk[1:0];
    else
        idlkq <= #TP {idlk[0], idlkq[3]};
end

//COM and EIDLE bits location
assign chk_com = {comk[3:0], comkq[3:1]};
assign chk_idl = {idlk[3:0], idlkq[3:2]};

//2 EIDLEs to ensure eios received on buffer pop side because no COM pushed in for bare-COM enhancement
assign pre_deskew_see_idl_os =  /*chk_com[1] &*/ enuf(chk_idl[4:2])
                           | /*chk_com[2] &*/ enuf(chk_idl[5:3])
                           | /*chk_com[3] &*/ enuf(chk_idl[6:4])
                           | /*chk_com[4] &*/ enuf(chk_idl[7:5]);
assign deskew_see_idl_os = (smlh_flit_mode_enable) ? (pre_deskew_see_idl_os && ~ltssm_in_l0p) : pre_deskew_see_idl_os;

// function to determine when enough IDL symbols are detected.
function automatic enuf;
input [2:0] chk;
begin
// Spec requires 2 of 3 valid IDL characters. RocketIO needs weaker checking
     enuf =  chk[0] & chk[1]
           | chk[1] & chk[2]
           | chk[0] & chk[2];
end
endfunction // enuf

//logic below for deasserting deskew_rxdata_dv immediately when detecting an EIOS
always @(posedge core_clk or negedge core_rst_n) begin : latched_deskew_see_idl_os_PROC
    if (~core_rst_n)
        latched_deskew_see_idl_os <= #TP 1'h0;
    //if deskew_see_idl_os, no deskew_enable, no push to deskew buffer
    //then buffer will be empty, then !int_rxvalid (!deskew_rxdata_dv_i)
    else if (deskew_bypass ? !deskew_enable : !int_rxvalid)
        //if deskew_bypass, when deskew_enable=0, reset latched_deskew_see_idl_os
        latched_deskew_see_idl_os <= #TP 1'b0;
    else if (pre_deskew_see_idl_os)
        latched_deskew_see_idl_os <= #TP 1'b1;
end

assign int_deskew_see_idl_os = latched_deskew_see_idl_os || deskew_flit_eios_det_g12;

always @(posedge core_clk or negedge core_rst_n) begin : slv_do_deskew_d_PROC
    if (~core_rst_n)
        slv_do_deskew_d <= #TP 1'b0;
    else
        slv_do_deskew_d <= #TP slv_do_deskew;
end // slv_do_deskew_d_PROC

// artificially make a SKP symbol to reset pkt_finder after deskew_enable deassertion for sris at gen1/2 rate
// this is safe because slv_do_deskew=0 makes deskew_rxdat_dv = 0. Here is manually making a pulse with deskew_rxdat_dv = 1 on all lanes with skp symbol at the same cycle
// do not need extra_k_sris_flag pulse because the core has deskew_rxdata_flush_gen12 signal to pkt_finder to indicate the deskew ends.
assign extra_k_sris_flag = 0; //~slv_do_deskew & slv_do_deskew_d & (current_data_rate == `GEN1_RATE || current_data_rate == `GEN2_RATE) & cfg_ts2_lid_deskew & ~deskew_bypass;

   always @(posedge core_clk or negedge core_rst_n)
     if (~core_rst_n)
        prev_com_reg <= #TP 1'b0;
     else if (~slv_do_deskew)
        prev_com_reg <= #TP 1'b0;
     else
        prev_com_reg <= #TP ~int_rxdata_dv ? prev_com_reg    : // if the rxdata is not valid, then keep the previous value
                              active_nb[2] ? rxdata_comma[3] : // 4s
                              active_nb[1] ? rxdata_comma[1] : // 2s
                                             rxdata_comma[0] ; // 1s

   always @(posedge core_clk or negedge core_rst_n)
     if (~core_rst_n)
        prev_skp_reg <= #TP 1'b0;
     else if (~slv_do_deskew)
        prev_skp_reg <= #TP 1'b0;
     else
        prev_skp_reg <= #TP ~int_rxdata_dv ? prev_skp_reg   :  // if the rxdata is not valid, then keep the previous value
                              active_nb[2] ? rxdata_skip[3] :  // 4s
                              active_nb[1] ? rxdata_skip[1] :  // 2s
                                             rxdata_skip[0] ;  // 1s

   always @(posedge core_clk or negedge core_rst_n) begin : prev_skprm_reg_PROC
     if (~core_rst_n)
        prev_skprm_reg <= #TP 1'b0;
     else if (~slv_do_deskew)
        prev_skprm_reg <= #TP 1'b0;
     else
        prev_skprm_reg <= #TP ~int_rxdata_dv ? prev_skprm_reg   :  // if the rxdata is not valid, then keep the previous value
                                active_nb[2] ? rxdata_skprm[3] :  // 4s
                                active_nb[1] ? rxdata_skprm[1] :  // 2s
                                               rxdata_skprm[0] ;  // 1s
   end // prev_skprm_reg_PROC

   always @(posedge core_clk or negedge core_rst_n)
     if (~core_rst_n)
        prev_ts2_reg <= #TP 1'b0;
     else if (~slv_do_deskew) 
        prev_ts2_reg <= #TP 1'b0;
     else
        prev_ts2_reg <= #TP ~int_rxdata_dv ? prev_ts2_reg   :  // if the rxdata is not valid, then keep the previous value
                              active_nb[2] ? smseq_loc_ts2_rcvd[3] :  // 4s
                              active_nb[1] ? smseq_loc_ts2_rcvd[1] :  // 2s
                                             smseq_loc_ts2_rcvd[0] ;  // 1s

   always @(posedge core_clk or negedge core_rst_n)
     if (~core_rst_n)
        prev_eies_reg <= #TP 1'b0;
     else if (~slv_do_deskew) 
        prev_eies_reg <= #TP 1'b0;
     else
        prev_eies_reg <= #TP ~int_rxdata_dv ? prev_eies_reg   :  // if the rxdata is not valid, then keep the previous value
                               active_nb[2] ? smseq_loc_eies_rcvd[3] :  // 4s
                               active_nb[1] ? smseq_loc_eies_rcvd[1] :  // 2s
                                              smseq_loc_eies_rcvd[0] ;  // 1s

   always @(posedge core_clk or negedge core_rst_n)
     if (~core_rst_n)
        prev_com_followed_by_skp_reg <= #TP 1'b0;
     else if (~slv_do_deskew)
        prev_com_followed_by_skp_reg <= #TP 1'b0;
     else
        prev_com_followed_by_skp_reg <= #TP ~int_rxdata_dv ? prev_com_followed_by_skp_reg    : // if the rxdata is not valid, then keep the previous value
                              active_nb[2] ? radata_com_followed_by_skp[3] : // 4s
                              active_nb[1] ? radata_com_followed_by_skp[1] : // 2s
                                             radata_com_followed_by_skp[0] ; // 1s

// Note: priority encoded
   wire [NB-1:0] load_rxvec0; // load signal for byte lane 0 (from rxdata), before byte shifting
   assign load_rxvec0 =  write_rxword[0] ? (1'b1 << 0)
                       : write_rxword[1] ? (1'b1 << 1)
                       : write_rxword[2] ? (1'b1 << 2)
                       : write_rxword[3] ? (1'b1 << 3)
                       : {NB{1'h0}};
   wire [NB-1:1] load_rxvec1; // load signal for byte lane 1 (from rxdata), before byte shifting
   assign load_rxvec1 =  (~load_rxvec0[1] & write_rxword[1]) ? (1'b1 << 0)
                       : (~load_rxvec0[2] & write_rxword[2]) ? (1'b1 << 1)
                       : (~load_rxvec0[3] & write_rxword[3]) ? (1'b1 << 2)
                       : {NB-1{1'h0}};
   wire [NB-1:2] load_rxvec2; // load signal for byte lane 2 (from rxdata), before byte shifting
   assign load_rxvec2 =  (~load_rxvec1[2] & ~load_rxvec0[2] & write_rxword[2]) ? (1'b1 << 0)
                       : (~load_rxvec1[3] & ~load_rxvec0[3] & write_rxword[3]) ? (1'b1 << 1)
                       : {NB-1{1'h0}};

   wire [NB-1:3] load_rxvec3; // load signal for byte lane 3 (from rxdata), before byte shifting
   assign load_rxvec3 =  (~load_rxvec2[3] & ~load_rxvec1[3] & ~load_rxvec0[3] & write_rxword[3]) ? (1'b1 << 0)
                       : {NB-1{1'h0}};

   always @(posedge core_clk or negedge core_rst_n)
     if (~core_rst_n)
       found_lock_reg <= #TP 1'b0;
     else if (~deskew_enable)
       found_lock_reg <= #TP 1'b0;
     else if (|found_lock_wire)
       found_lock_reg <= #TP 1'b1;

   assign found_lock = (deskew_enable & |found_lock_wire) | found_lock_reg;

// We consider the first character after a comma to be the "lock" point
// or the first idle data symbol following the last ts2/skp received if CPCIE && cfg_ts2_lid_deskew==1
   assign found_lock_wire = (smlh_in_rl0s && cfg_ts2_lid_deskew) ? // Rx.L0s, detecting skp only ok because the remote only transmits one SKP following FTS in Tx.L0s state
                             (({
                               {NB-4{1'b0}},
                               active_nb[2] & (rxdata_skprm[3] ? 1'b1 : (rxdata_comma[2] & ~rxdata_skprm[2] & rxdata_skip[3])),
                               active_nb[2] & (rxdata_skprm[2] ? 1'b1 : (rxdata_comma[1] & ~rxdata_skprm[1] & rxdata_skip[2])),
                               |active_nb[2:1] & (rxdata_skprm[1] ? 1'b1 : (rxdata_comma[0] & ~rxdata_skprm[0] & rxdata_skip[1])),
                               rxdata_skprm[0] ? 1'b1 : (prev_com_reg & ~prev_skprm_reg & rxdata_skip[0])
                              }) & write_rxword_unmask
                             ) // Rx.L0s
                            :
                            ((~ltssm_lpbk_master || smlh_flit_mode_enable) && skp_lid_lock_point && cfg_ts2_lid_deskew) ? // skp->idle, but not for ltssm_lpbk_master
                             (({
                               {NB-4{1'b0}},
                               active_nb[2] & ((rxdata_skip[2]) & rx_idle_data[3]),
                               active_nb[2] & ((rxdata_skip[1]) & rx_idle_data[2]),
                               |active_nb[2:1] & ((rxdata_skip[0]) & rx_idle_data[1]),
                               ((prev_skp_reg) & rx_idle_data[0])
                              }) & write_rxword_unmask
                             ) // skp->idle
                            :
                            (~ltssm_lpbk_master && up_skp_data_lock_point) ? // skp->data, but not for ltssm_lpbk_master
                             (({
                               {NB-4{1'b0}},
                               active_nb[2] & ((rxdata_skip[2]) & rx_data_char[3]),
                               active_nb[2] & ((rxdata_skip[1]) & rx_data_char[2]),
                               |active_nb[2:1] & ((rxdata_skip[0]) & rx_data_char[1]),
                               ((prev_skp_reg) & rx_data_char[0])
                              }) & write_rxword_unmask
                             ) // skp->data
                            :
                             (({
                               {NB-4{1'b0}},
                               active_nb[2] & ((smseq_loc_ts2_rcvd[2] | smseq_loc_eies_rcvd[2]) & rx_idle_data[3]),
                               active_nb[2] & ((smseq_loc_ts2_rcvd[1] | smseq_loc_eies_rcvd[1]) & rx_idle_data[2]),
                               |active_nb[2:1] & ((smseq_loc_ts2_rcvd[0] | smseq_loc_eies_rcvd[0]) & rx_idle_data[1]),
                               ((prev_ts2_reg | prev_eies_reg) & rx_idle_data[0])
                               } & {NB{cfg_ts2_lid_deskew}}) | // ts2/eieos->idle
                               {
                                 {NB-4{1'b0}},
                                 active_nb[2] & ((rxdata_comma[2] & ~rxdata_skprm[2]) | rxdata_skprm[3]),
                                 active_nb[2] & ((rxdata_comma[1] & ~rxdata_skprm[1]) | rxdata_skprm[2]),
                                 |active_nb[2:1] & ((rxdata_comma[0] & ~rxdata_skprm[0]) | rxdata_skprm[1]),
                               ((prev_com_reg & ~prev_skprm_reg) | rxdata_skprm[0])}
                             ) & write_rxword_unmask // next symbol to comma
                            ;  // just pull out the lock points from write_rxword_unmask
                               // Note that write_rxword_unmask also gets asserted for
                               // non-previous commas

   // write_rxword is high when this particular byte should be written into the fifos
   // NOTE: before byte shifting

wire [NB-1:0] write_lock_word;

   // if you haven't found lock yet, then only write in the bytes that are after the lock point
   assign write_lock_word =  {NB{found_lock_reg}}
                           | (~deskew_enable      ? {{NB-4{1'b0}}, 4'b0000} :
                               found_lock_wire[0] ? {{NB-4{1'b0}}, 4'b1111} :
                               found_lock_wire[1] ? {{NB-4{1'b0}}, 4'b1110} :
                               found_lock_wire[2] ? {{NB-4{1'b0}}, 4'b1100} :
                               found_lock_wire[3] ? {{NB-4{1'b0}}, 4'b1000} : {NB{1'b0}})
                           ;

   assign write_rxword = write_lock_word & write_rxword_unmask;

assign look_for_alignment = slv_do_deskew & ~deskew_overflow_i & ~deskew_flit_eios_det_g12_d; // if flit mode is enabled, this signal is cleared by an eios detection at 8b/10b encoding

   // in order to support infinite deskew, we must detect a transition between receiving TS1s and TS2s
always @(posedge core_clk or negedge core_rst_n)
    if (~core_rst_n) begin
        ts_state       <= #TP 5'h0;
        ts_state[IDLE] <= #TP 1'b1;
    end else if ( cxl_mode_enable && (current_data_rate > `GEN2_RATE) ) begin
        ts_state[IDLE] <= #TP 1'b1;
    end else if ( deskew_latched_l0p_ei_rcvd ) begin
        ts_state[IDLE] <= #TP 1'b1;
    end else
        ts_state       <= #TP next_ts_state;

assign     next_ts_state = ns_ts_gen(ts_state, look_for_alignment, smseq_ts1_rcvd_pulse, smseq_ts2_rcvd_pulse, found_lock_wire, deskew_bypass);

function automatic [4:0] ns_ts_gen;
    input [4:0] ts_state;
    input look_for_alignment;
    input smseq_ts1_rcvd_pulse;
    input smseq_ts2_rcvd_pulse;
    input [NB-1:0] found_lock_wire;
    input deskew_bypass;
    reg [4:0] result;
    begin
        result = 5'h0;

             case (1'b1)
            ts_state[IDLE]:
                if (look_for_alignment & smseq_ts1_rcvd_pulse)
                    result[TS1_RCVD]    = 1'b1;
                else if (look_for_alignment & smseq_ts2_rcvd_pulse & deskew_bypass) // if deskew_bypass, no skew across lanes, so detecting TS2 is to enable deskew_rxdata_dv
                    result[TS2_RCVD]    = 1'b1;
                else
                    result[IDLE]        = 1'b1;
            ts_state[TS1_RCVD]:
                if (look_for_alignment & smseq_ts2_rcvd_pulse)
                    result[TS2_RCVD]    = 1'b1;
                else if (~look_for_alignment)
                    result[IDLE]    = 1'b1;
                else
                    result[TS1_RCVD]    = 1'b1;
            ts_state[TS2_RCVD]:
                if (look_for_alignment & |found_lock_wire)
                    result[SUCCESS]     = 1'b1;
                else if (look_for_alignment & smseq_ts2_rcvd_pulse)
                    result[ALIGN_ERROR] = 1'b1;
                else if (~look_for_alignment)
                    result[IDLE]    = 1'b1;
                else
                    result[TS2_RCVD]    = 1'b1;
            ts_state[ALIGN_ERROR]:
                if (~look_for_alignment)
                    result[IDLE]        = 1'b1;
                else
                    result[ALIGN_ERROR] = 1'b1;
            default: // ts_state[SUCCESS]
                if (~look_for_alignment)
                    result[IDLE]        = 1'b1;
                else
                    result[SUCCESS] = 1'b1;
        endcase // case(1'b1)
        ns_ts_gen = result;
    end
endfunction

assign ts_do_deskew = next_ts_state[TS2_RCVD] | ts_state[TS2_RCVD] | ts_state[SUCCESS];

always @(posedge core_clk or negedge core_rst_n)
  if (~core_rst_n)
      skp_do_deskew_reg <= #TP 1'b0;
  else if (~look_for_alignment || ((smlh_flit_mode_enable && ltssm_lpbk_master) ? sft_falling_edge : 1'b0))
      skp_do_deskew_reg <= #TP 1'b0;
  else if (skp_lock_point)
      skp_do_deskew_reg <= #TP 1'b1;

always @(posedge core_clk or negedge core_rst_n)
    if (~core_rst_n)      
        skp_do_deskew_r <= #TP 1'b0;
    else
        skp_do_deskew_r <= #TP skp_do_deskew;

// use ts2/skp -> Logic Idle Data Transition to do deskew
always @( * ) begin : i_rxdata_PROC // max 4 bytes for Gen1/2
    i_rxdata = 32'hFFFFFFFF;

    i_rxdata = {
               rxdata[31:16],

               rxdata[15:8],

               rxdata[7:0]
               };
end // i_rxdata_PROC

always @( * ) begin : i_rxdatak_PROC // max 4 bytes for Gen1/2
    i_rxdatak = 4'hF;

    i_rxdatak = {
               rxdatak_i[3:2],

               rxdatak_i[1],

               rxdatak_i[0]
               };
end // i_rxdatak_PROC

always @( * ) begin : i_rxerror_PROC // max 4 bytes for Gen1/2
    i_rxerror = 4'hF;

    i_rxerror = {
               rxerror[3:2],

               rxerror[1],

               rxerror[0]
               };
end // i_rxerror_PROC

// rxvalid = 1 & rxdatavalid = 1, no k-char, no Rx Error, rxdata[8 bits] must be 8'h0
assign rx_idle_data = {4{rxdata_dv}} & ~i_rxdatak & ~i_rxerror & {i_rxdata[31:24]==8'h0, i_rxdata[23:16]==8'h0, i_rxdata[15:8]==8'h0, i_rxdata[7:0]==8'h0};
assign rx_data_char = {4{rxdata_dv}} & ~i_rxdatak & ~i_rxerror;

always @( posedge core_clk or negedge core_rst_n) begin : dly_loc_ts2_rcvd_PROC
    if ( ~core_rst_n ) begin
        dly_loc_ts2_rcvd <= #TP 0;
        dly_in_skp       <= #TP 0;
        dly_loc_eies_rcvd <= #TP 0;
    end else if ( ~rxaligned ) begin // if rxvalid, no ts2 or skp rcvd
        dly_loc_ts2_rcvd <= #TP 0;
        dly_in_skp       <= #TP 0;
        dly_loc_eies_rcvd <= #TP 0;
    end else if ( cfg_elastic_buffer_mode && ~rxdata_dv ) begin // if rxdatavalid=0 & cfg_elastic_buffer_mode (empty), keep previous value
        dly_loc_ts2_rcvd <= #TP dly_loc_ts2_rcvd;
        dly_in_skp       <= #TP dly_in_skp;
        dly_loc_eies_rcvd <= #TP dly_loc_eies_rcvd;
    end else begin
        dly_loc_ts2_rcvd <= #TP smseq_loc_ts2_rcvd;
        dly_in_skp       <= #TP smseq_in_skp;
        dly_loc_eies_rcvd <= #TP smseq_loc_eies_rcvd;
    end
end // dly_loc_ts2_rcvd_PROC

always @( * ) begin : ts2_lid_lock_point_PROC
    ts2_lid_lock_point = 0;

    if ( active_nb == 1 ) begin // 1s
        ts2_lid_lock_point = dly_loc_ts2_rcvd[0] & rx_idle_data[0]; // previous cycle byte 0 is ts2 rcvd AND current cycle byte 0 is idle data
    end else if ( active_nb == 2 ) begin
        // current cycle byte 0 is ts2 rcvd AND current cycle byte 1 is idle data
        // previous cycle byte 1 is ts2 rcvd AND current cycle byte 0 is idle data
        ts2_lid_lock_point = (smseq_loc_ts2_rcvd[0] & rx_idle_data[1]) | (dly_loc_ts2_rcvd[1] & rx_idle_data[0]);
    end else if ( active_nb == 4 ) begin
        // current cycle byte 0 is ts2 rcvd AND current cycle byte 1 is idle data
        // current cycle byte 1 is ts2 rcvd AND current cycle byte 2 is idle data
        // current cycle byte 2 is ts2 rcvd AND current cycle byte 3 is idle data
        // previous cycle byte 3 is ts2 rcvd AND current cycle byte 0 is idle data
        ts2_lid_lock_point = (smseq_loc_ts2_rcvd[0] & rx_idle_data[1]) | (smseq_loc_ts2_rcvd[1] & rx_idle_data[2]) | (smseq_loc_ts2_rcvd[2] & rx_idle_data[3]) | (dly_loc_ts2_rcvd[3] & rx_idle_data[0]);
    end
end // ts2_lid_lock_point_PROC

always @( * ) begin : eies_lid_lock_point_PROC
    eies_lid_lock_point = 0;

    if ( active_nb == 1 ) begin // 1s
        eies_lid_lock_point = dly_loc_eies_rcvd[0] & rx_idle_data[0]; // previous cycle byte 0 is eieos rcvd AND current cycle byte 0 is idle data
    end else if ( active_nb == 2 ) begin
        // current cycle byte 0 is eieos rcvd AND current cycle byte 1 is idle data
        // previous cycle byte 1 is eieos rcvd AND current cycle byte 0 is idle data
        eies_lid_lock_point = (smseq_loc_eies_rcvd[0] & rx_idle_data[1]) | (dly_loc_eies_rcvd[1] & rx_idle_data[0]);
    end else if ( active_nb == 4 ) begin
        // current cycle byte 0 is eieos rcvd AND current cycle byte 1 is idle data
        // current cycle byte 1 is eieos rcvd AND current cycle byte 2 is idle data
        // current cycle byte 2 is eieos rcvd AND current cycle byte 3 is idle data
        // previous cycle byte 3 is eieos rcvd AND current cycle byte 0 is idle data
        eies_lid_lock_point = (smseq_loc_eies_rcvd[0] & rx_idle_data[1]) | (smseq_loc_eies_rcvd[1] & rx_idle_data[2]) | (smseq_loc_eies_rcvd[2] & rx_idle_data[3]) | (dly_loc_eies_rcvd[3] & rx_idle_data[0]);
    end
end // eies_lid_lock_point_PROC

// if a wrong idle data occurs between SKP Symbols in a SKP OS, the deskew logic will have deskew_skp_alignment_err. So no worry about this
always @( * ) begin : skp_lid_lock_point_PROC
    skp_lid_lock_point = 0;

    if ( active_nb == 1 ) begin // 1s
        skp_lid_lock_point = dly_in_skp[0] & rx_idle_data[0]; // previous cycle byte 0 is skp rcvd AND current cycle byte 0 is idle data
    end else if ( active_nb == 2 ) begin
        // current cycle byte 0 is skp rcvd AND current cycle byte 1 is idle data
        // previous cycle byte 1 is skp rcvd AND current cycle byte 0 is idle data
        skp_lid_lock_point = (smseq_in_skp[0] & rx_idle_data[1]) | (dly_in_skp[1] & rx_idle_data[0]);
    end else if ( active_nb == 4 ) begin
        // current cycle byte 0 is skp rcvd AND current cycle byte 1 is idle data
        // current cycle byte 1 is skp rcvd AND current cycle byte 2 is idle data
        // current cycle byte 2 is skp rcvd AND current cycle byte 3 is idle data
        // previous cycle byte 3 is skp rcvd AND current cycle byte 0 is idle data
        skp_lid_lock_point = (smseq_in_skp[0] & rx_idle_data[1]) | (smseq_in_skp[1] & rx_idle_data[2]) | (smseq_in_skp[2] & rx_idle_data[3]) | (dly_in_skp[3] & rx_idle_data[0]);
    end
end // skp_lid_lock_point_PROC

// Detect symbols following SKP-OS (Flit or TS-OS/EIEOS)
wire    [3:0]           rx_com_char;
wire    [3:0]           rx_without_com;
reg     [3:0]           i_rxdata_comma;
reg     [3:0]           rx_com_char_d;
reg     [3:0]           dly_in_skp_dd;
reg                     skp_os_lock_point;
always @( * ) begin : i_rxdata_comma_PROC // max 4 bytes for Gen1/2
    i_rxdata_comma= 4'hF;
    i_rxdata_comma= {
               rxdata_comma[3:2],
               rxdata_comma[1],
               rxdata_comma[0]
               };
end // i_rxdata_comma_PROC

assign rx_com_char    = {4{rxdata_dv}} & i_rxdatak & i_rxdata_comma & ~smseq_in_skp & ~i_rxerror;
assign rx_without_com = {4{rxdata_dv}} & ~(i_rxdatak & i_rxdata_comma) & ~smseq_in_skp & ~i_rxerror;
always @( * ) begin : skp_data_lock_point_PROC
    skp_data_lock_point = 0;
    skp_os_lock_point   = 0;
    up_skp_data_lock_point = 0;

    if ( active_nb == 1 ) begin // 1s
        skp_data_lock_point = dly_in_skp[0] & rx_data_char[0]; // previous cycle byte 0 is skp rcvd AND current cycle byte 0 is idle data
        skp_os_lock_point   = dly_in_skp_dd[0] & rx_com_char_d[0] & rx_without_com[0];
    end else if ( active_nb == 2 ) begin
        // current cycle byte 0 is skp rcvd AND current cycle byte 1 is idle data
        // previous cycle byte 1 is skp rcvd AND current cycle byte 0 is idle data
        skp_data_lock_point = (smseq_in_skp[0] & rx_data_char[1]) | (dly_in_skp[1] & rx_data_char[0]);
        skp_os_lock_point   = (dly_in_skp[1] & rx_com_char[0] & rx_without_com[1]) | (dly_in_skp[0] & rx_com_char_d[1] & rx_without_com[0]);
    end else if ( active_nb == 4 ) begin
        // current cycle byte 0 is skp rcvd AND current cycle byte 1 is idle data
        // current cycle byte 1 is skp rcvd AND current cycle byte 2 is idle data
        // current cycle byte 2 is skp rcvd AND current cycle byte 3 is idle data
        // previous cycle byte 3 is skp rcvd AND current cycle byte 0 is idle data
        skp_data_lock_point = (smseq_in_skp[0] & rx_data_char[1]) | (smseq_in_skp[1] & rx_data_char[2]) | (smseq_in_skp[2] & rx_data_char[3]) | (dly_in_skp[3] & rx_data_char[0]);
        skp_os_lock_point   = (smseq_in_skp[1] & rx_com_char[2] & rx_without_com[3]) | (smseq_in_skp[0] & rx_com_char[1] & rx_without_com[2]) | (dly_in_skp[3] & rx_com_char[0] & rx_without_com[1]) | (dly_in_skp[2] & rx_com_char_d[3] & rx_without_com[0]);
    end
    up_skp_data_lock_point = skp_data_lock_point && (current_data_rate < `GEN3_RATE) && deskew_latched_l0p_ei_rcvd;
end // skp_data_lock_point_PROC

always @( posedge core_clk or negedge core_rst_n) begin : dly_l0p_char_rcvd_PROC
    if ( ~core_rst_n ) begin
        rx_com_char_d <= #TP 0;
        dly_in_skp_dd <= #TP 0;
    end else if (current_data_rate < `GEN3_RATE) begin
        if(rxdata_dv) begin
            rx_com_char_d <= #TP rx_com_char;
            dly_in_skp_dd <= #TP dly_in_skp;
        end else begin
            rx_com_char_d <= #TP rx_com_char_d;
            dly_in_skp_dd <= #TP dly_in_skp_dd;
        end
    end else begin
        rx_com_char_d <= #TP 0;
        dly_in_skp_dd <= #TP 0;
    end
end // dly_l0p_char_rcvd_PROC

// keep the lock point until ~look_for_alignment
always @(posedge core_clk or negedge core_rst_n) begin : latched_skp_data_lock_point_PROC
  if (~core_rst_n)
      latched_skp_data_lock_point <= #TP 1'b0;
  else if ( ~look_for_alignment || (smlh_flit_mode_enable && sft_falling_edge && ~(ltssm_in_l0p && l0p_lanes_active)))
      latched_skp_data_lock_point <= #TP 1'b0;
  else if ( up_skp_data_lock_point )
      latched_skp_data_lock_point <= #TP 1'b1;
end // latched_skp_data_lock_point_PROC

assign skp_data_do_deskew = up_skp_data_lock_point | latched_skp_data_lock_point;

// keep the lock point until ~look_for_alignment
always @(posedge core_clk or negedge core_rst_n) begin : latched_ts2_lid_lock_point_PROC
  if (~core_rst_n)    
      latched_ts2_lid_lock_point <= #TP 1'b0;
  else if ( ~look_for_alignment || (smlh_flit_mode_enable && sft_falling_edge) )
      latched_ts2_lid_lock_point <= #TP 1'b0;   
