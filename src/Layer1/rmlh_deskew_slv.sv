                          (skp_data_do_deskew) |       // because of skp -> Data transition for L0p
                          (skp_lid_do_deskew  && (cfg_ts2_lid_deskew)) |       // because of skp -> Idle_Data transition
                          (skp_do_deskew      && (cfg_ts2_lid_deskew && ltssm_lpbk_master && ~smlh_flit_mode_enable)) |       // because of skp detection, for loopback master only
