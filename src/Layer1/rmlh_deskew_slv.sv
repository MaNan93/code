input [14:0] d;
begin
    fun_margin_crc[0] = d[0] ^ d[3] ^ d[5] ^ d[6] ^ d[9]  ^ d[10] ^ d[11] ^ d[12] ^ d[13];
    fun_margin_crc[1] = d[1] ^ d[4] ^ d[6] ^ d[7] ^ d[10] ^ d[11] ^ d[12] ^ d[13] ^ d[14];
    fun_margin_crc[2] = d[0] ^ d[2] ^ d[3] ^ d[6] ^ d[7]  ^ d[8]  ^ d[9]  ^ d[10] ^ d[14];
    fun_margin_crc[3] = d[1] ^ d[3] ^ d[4] ^ d[7] ^ d[8]  ^ d[9]  ^ d[10] ^ d[11];
    fun_margin_crc[4] = d[2] ^ d[4] ^ d[5] ^ d[8] ^ d[9]  ^ d[10] ^ d[11] ^ d[12];
end
endfunction // fun_margin_crc

