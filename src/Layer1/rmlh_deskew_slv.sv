    else if ( deskew_enable && (ts2_lid_do_deskew || skp_lid_do_deskew || (ltssm_lpbk_master && smlh_ltssm_state == S_LPBK_ACTIVE) || fts_skp_do_deskew || eies_lid_do_deskew) )
