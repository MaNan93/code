//skp_end is one cycle pulse
//no skp_end for control skp which is for esm_25/20 or pcie gen4
assign int_skp_end =
                     (current_data_rate == `GEN4_RATE || current_data_rate == `GEN5_RATE || current_data_rate == `GEN6_RATE || gen3_flit_mode) ? 1'b0 :
                     (active_nb[2]) ? (rxdata_dv & rxdata_skip[0] & (rxdata[7:0]   == `SKP_END_SYM))  : // 4s
                     (active_nb[3])    ? (rxdata_dv & rxdata_skip[0] & (rxdata[39:32] == `SKP_END_SYM))  : // 8s
                                         1'b0                                                  //assume rxdata_skip is active during entire skp os
                     ;

//to prevent that 4N+2 might be `SKP_END_SYM
