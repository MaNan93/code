// -------------------------------------------------------------------------
// --- Module Description: XPLH CXL NOP flit generator
// --- Generates Physical Layer NOP flits in 256B Flit Mode
// --- Implements CXL.io Throttling
// --- Not applicable in 68B Flit Mode
//
// --- CXL Specificiation Reference:
// --- The Physical Layer must insert NOP flits when it backpressures the upper 
// --- layers due to its Tx retry buffer filling up; it is also required to insert 
// --- NOP flits when traffic is not generated by the upper layers.
// ---
// --- Physical Layer NOP flits carry 0s in the bit positions that correspond to the
// --- bit positions in CXL.io flits that are used to carry DLLP payload (indicated to
// --- XPLH Control with xplh_nop_phy_flit output signal); the remaining bits in 
// --- Physical Layer NOP flits are reserved.
//
// -----------------------------------------------------------------------------

`include "include/DWC_pcie_ctl_all_defs.svh"
`include "products/cx_pl_pkg.svh"
 
module xplh_phy_nop_gen 
    import cx_pl_pkg::tx_cmd_e;
    import cx_pl_pkg::CMD_RESET;
    import cx_pl_pkg::CMD_IDLE;
    import cx_pl_pkg::CMD_NOP;
    import cx_pl_pkg::CMD_PYLD;
    import cx_pl_pkg::tx_cmd_struct;
    import cx_pl_pkg::tx_flit_struct;
#(
    parameter   TP        = `TP,                                 // Clock to Q delay (simulator insurance)
    parameter   NW        = `CX_NW,                              // Number of 32-bit dwords handled by the datapath each clock. Note: mininum datapath is 128bits.
    parameter   DW        = (32*NW)                              // Width of datapath in bits.

) (
// Inputs ------------------------------------------------------------------------------
    input                                core_clk,               // Core Clock
    input                                core_rst_n,             // Core Reset
    input                                flit_mode_enable,       // PCIe Flit Mode enable
    input                                cxl_io_throttle_enable, // CXL.io Throttle (Required at 64GT/s)
    input   tx_cmd_struct                xplh_control_cmd,       // XPLH Control Command
    input   tx_flit_struct               xplh_retry_flit,        // XPLH Retry input flit structure
    input                                xplh_nop_gen_halt,      // NOP Generator halt
// Outputs -----------------------------------------------------------------------------
    output  logic                        xplh_nop_gen_ack,       // NOP Generator Command Acknowledge
    output  logic                        xplh_nop_phy_flit,      // Physical Layer NOP flit indication - do not allow DLLP insertion
    output  tx_flit_struct               xplh_nop_gen_flit,      // NOP Generator output flit structure
    output  logic                        xplh_retry_halt_out     // XPLH Retry halt
);

localparam DW_RATIO = 2048 / DW;  // Number of cycles required to complete 256B flit on the interface to ARB/MUX

logic [DW_RATIO-1:0]        xplh_nop_dv_cnt_nxt;          // XPLH NOP data valid counter - next state
logic [DW_RATIO-1:0]        xplh_nop_dv_cnt_r;            // XPLH NOP data valid counter
logic                       xplh_nop_gen_vld;             // XPLH NOP Generator Flit Valid
logic                       xplh_nop_gen_sof;             // XPLH NOP Generator Flit SOF flag
logic [1:0]                 xplh_nop_gen_eof;             // XPLH NOP Generator Flit EOF flag
logic                       xplh_nop_gen_enf;             // XPLH NOP Generator Flit ENF flag
logic                       xplh_nop_gen_enable_nxt;      // XPLH NOP Generator enable - next state
logic                       xplh_nop_gen_enable_r;        // XPLH NOP Generator enable
logic                       xplh_nop_gen_enable;          // Enable CXL Physical Layer NOP Generator
logic                       xplh_nop_gen_idle;            // NOP Generator does not process Payload flits
logic                       xplh_nop_gen_last;            // XPLH NOP flit generated after the last flit on Payload datapath
logic                       xplh_payload_enable_nxt;      // XPLH Payload datapath enable - next state
logic                       xplh_payload_enable_r;        // XPLH Payload datapath enable
logic                       xplh_retry_active_nxt;        // Flit is in progress on XPLH Retry IF - next state
logic                       xplh_retry_active_r;          // Flit is in progress on XPLH Retry IF
logic                       xplh_io_flit_det_nxt;         // CXL.io flit is being transmitted on XPLH interface - next state
logic                       xplh_io_flit_det_r;           // CXL.io flit is being transmitted on XPLH interface - register state
logic                       xplh_io_flit_sof_s;           // CXL.io flit indication on XPLH flit interface
logic                       xplh_io_flit_req_s;           // Physical Layer NOP flit insertion request after CXL.io flit

// Output assignments
assign xplh_retry_halt_out = xplh_nop_gen_halt || (flit_mode_enable && (!xplh_nop_gen_sof || !xplh_payload_enable_r || xplh_io_flit_req_s));

// Internal assignments
assign xplh_nop_gen_vld    = xplh_nop_dv_cnt_r[0];
assign xplh_nop_gen_sof    = xplh_nop_dv_cnt_r[DW_RATIO-1];
assign xplh_nop_gen_eof    = (xplh_nop_dv_cnt_r[1:0] == 2'b01) ? 2'b11 : 2'b00;
assign xplh_nop_gen_enf    = (xplh_nop_dv_cnt_r[1:0] == 2'b01);

// NOP Generator is enabled in PCIe Flit Mode when XPLH command is not in CMD_RESET or CMD_IDLE
assign xplh_nop_gen_enable = flit_mode_enable ? !(xplh_control_cmd.tx_cmd inside {CMD_RESET, CMD_IDLE}) : 1'b0;
// Idle indication when NOP Generator is not enabled or there are no payload flits on the interface
// It is used by XPLH Control to acknowledge FLUSH commands from SPLH.
// Payload flits are expected to be stalled by stall_req/ack handshake on SPIF interface before SPLH requests FLUSH command.
assign xplh_nop_gen_idle = xplh_nop_gen_enable ? !xplh_payload_enable_r : 1'b1;
// Asserted on EOF cycle of the NOP flit generated after the last flit on the Payload datapath
assign xplh_nop_gen_last   = !xplh_retry_flit.data_valid && xplh_nop_gen_flit.eof[1] && !xplh_nop_gen_halt;

// In CXL mode, select Physical Layer NOP when NOP Generator is enabled and there is valid flit on
// XPLH Retry interface, or CXL.io throttling request is asserted between back-to-back CXL.io flits
// In PCIe mode, always select a flit XPLH Retry interface
assign xplh_nop_gen_sel    = flit_mode_enable && !xplh_retry_active_r && !(xplh_retry_flit.data_valid && xplh_nop_gen_sof && xplh_payload_enable_r && !xplh_io_flit_req_s);

// NOP Generator Output Mux
always_comb begin
    if (xplh_nop_gen_sel) begin
        xplh_nop_phy_flit            = 1'b1;
        xplh_nop_gen_flit            = '0;
        xplh_nop_gen_flit.data_valid = xplh_nop_gen_vld;
        xplh_nop_gen_flit.sof        = xplh_nop_gen_sof;
        xplh_nop_gen_flit.eof        = xplh_nop_gen_eof;
        xplh_nop_gen_flit.enf        = xplh_nop_gen_enf;
        xplh_nop_gen_flit.expl_flit  = xplh_retry_flit.expl_flit && xplh_payload_enable_r;
        xplh_nop_gen_flit.retry_flit = xplh_retry_flit.retry_flit && xplh_payload_enable_r;
    end
    else begin
        xplh_nop_phy_flit            = 1'b0;
        xplh_nop_gen_flit            = xplh_retry_flit;
    end
end

always_comb begin
    if (xplh_control_cmd.req) begin
        case (xplh_control_cmd.tx_cmd)
            CMD_NOP : xplh_nop_gen_ack = xplh_nop_gen_enable_r && xplh_nop_gen_sof;
            CMD_PYLD: xplh_nop_gen_ack = xplh_payload_enable_r && xplh_nop_gen_sof;
            default : xplh_nop_gen_ack = xplh_nop_gen_idle;
        endcase
    end else begin
        xplh_nop_gen_ack = 1'b0;
    end
end

always_comb begin
    // Reset NOP Enable flag if CMD_RESET is requested
    if (xplh_control_cmd.tx_cmd == CMD_RESET)
        xplh_nop_gen_enable_nxt = 1'b0;
    // Set NOP Enable flag if CMD_PYLD is requested
    else if (xplh_nop_gen_enable && xplh_control_cmd.req && (xplh_control_cmd.tx_cmd == CMD_NOP))
        xplh_nop_gen_enable_nxt = 1'b1;
    // Reset NOP Enable flag on the last flit cycle when CMD_IDLE is requested
    else if (!xplh_nop_gen_enable && xplh_nop_gen_last)
        xplh_nop_gen_enable_nxt = 1'b0;
    else
        xplh_nop_gen_enable_nxt = xplh_nop_gen_enable_r;
end

always_comb begin
    // Set Payload Enable flag if CMD_PYLD is requested
    if (xplh_nop_gen_enable && xplh_control_cmd.req && (xplh_control_cmd.tx_cmd == CMD_PYLD))
        xplh_payload_enable_nxt = 1'b1;
    // Reset Payload Enable flag if CMD_RESET, CMD_IDLE, or CMD_NOP is requested
    else if (xplh_control_cmd.req && (xplh_control_cmd.tx_cmd != CMD_PYLD) && xplh_nop_gen_last)
        xplh_payload_enable_nxt = 1'b0;
    else
        xplh_payload_enable_nxt = xplh_payload_enable_r;
end

// NOP Generator Data Valid counter
always_comb begin
    // Reset counter if CMD_RESET is requested
    if (xplh_control_cmd.tx_cmd == CMD_RESET)
        xplh_nop_dv_cnt_nxt = {DW_RATIO{1'b0}};
    // If NOP Generator is enabled at EOF cycle of the current NOP flit the continue generating NOP flits
    // If NOP Generator is enabled and there is no valid NOP flit then start generating NOP flits
    else if (xplh_nop_gen_enable_r && ((xplh_nop_gen_eof[1] && !xplh_nop_gen_halt) || !xplh_nop_gen_vld))
        xplh_nop_dv_cnt_nxt = {DW_RATIO{1'b1}};
    // If Physical Layer NOP flit is selected on the output mux then progress NOP flit if halt is not asserted
    else if (xplh_nop_gen_sel && xplh_nop_gen_vld && !xplh_nop_gen_halt)
        xplh_nop_dv_cnt_nxt = xplh_nop_dv_cnt_r >> 1;
    else
        xplh_nop_dv_cnt_nxt = xplh_nop_dv_cnt_r;
end

// Flit is in progress on XPLH Retry Interface
always_comb begin
    // If flit is started on XPLH Retry interface (SOF cycle), set XPLH Retry Active flag
    if (!xplh_nop_gen_sel && xplh_retry_flit.sof && !xplh_nop_gen_halt)
        xplh_retry_active_nxt = 1'b1;
    // If flit is ended on XPLH Retry interface (EOF cycle), reset XPLH Retry Active flag
    else if (xplh_retry_flit.eof[1] && !xplh_nop_gen_halt)
        xplh_retry_active_nxt = 1'b0;
    else
        xplh_retry_active_nxt = xplh_retry_active_r;
end

always_ff @(posedge core_clk or negedge core_rst_n) begin
    if (!core_rst_n) begin
        xplh_nop_dv_cnt_r     <= #TP '0;
        xplh_nop_gen_enable_r <= #TP 1'b0;
        xplh_payload_enable_r <= #TP 1'b0;
        xplh_retry_active_r   <= #TP 1'b0;
    end
    else begin
        xplh_nop_dv_cnt_r     <= #TP xplh_nop_dv_cnt_nxt;
        xplh_nop_gen_enable_r <= #TP xplh_nop_gen_enable_nxt;
        xplh_payload_enable_r <= #TP xplh_payload_enable_nxt;
        xplh_retry_active_r   <= #TP xplh_retry_active_nxt;
    end
end

// -------------------------------------------------------------------------------------
// CXL.io Throttling Feature: inserts Physical Layer NOP flit between back-to-back CXL.io flits
// -------------------------------------------------------------------------------------
assign xplh_io_flit_req_s = xplh_io_flit_det_r && xplh_io_flit_sof_s;

// CXL.io Flit is starting on XPLH Retry interface (FlitUsage == 2'b01)
assign xplh_io_flit_sof_s = xplh_retry_flit.data_valid && xplh_retry_flit.sof && (xplh_retry_flit.data[7:6] == 2'b01);

always_comb begin
    // if CXL.io throttling is enabled then set CXL.io flit flag once CXL.io SOF cycle is accepted on XPLH Retry flit interface
    if (cxl_io_throttle_enable && xplh_io_flit_sof_s && !xplh_retry_halt_out) begin
         xplh_io_flit_det_nxt = 1'b1;
    end
    // If CXL.io flit flag is set then clear the flag on SOF cycle of the next flit on NOP Generator interface
    else if (xplh_io_flit_det_r && xplh_nop_gen_flit.sof && !xplh_nop_gen_halt) begin
         xplh_io_flit_det_nxt = 1'b0;
    end
    else begin
         xplh_io_flit_det_nxt = xplh_io_flit_det_r;
    end
end

always_ff @(posedge core_clk or negedge core_rst_n) begin
    if(!core_rst_n) begin
         xplh_io_flit_det_r <= #TP 'h0;
    end
    else begin
         xplh_io_flit_det_r <= #TP xplh_io_flit_det_nxt;
    end   
end
// -------------------------------------------------------------------------------------

endmodule // xplh_phy_nop_gen

